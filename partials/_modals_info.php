                <p class="fw-medium mb-1">AUDIT <span class="text-secondary fw-normal">(Alcohol Use Disorders Identification Test)</span></p>
                <p class="text-secondary small">
                    Fragebogen der WHO zur Selbstauskunft: 10 Fragen, je 0&ndash;4 Punkte, Summe 0&ndash;40.
                    Die Fragen 1&ndash;3 erfassen die Konsummenge, 4&ndash;6 Anzeichen von Abhängigkeit,
                    7&ndash;10 bereits eingetretene Folgeschäden. Der AUDIT ist international der
                    verbreitetste Kurztest auf riskanten Alkoholkonsum.
                </p>

                <p class="fw-medium mb-1 mt-3">LAST <span class="text-secondary fw-normal">(Lübecker Alkoholabhängigkeits- und -missbrauchs-Screening-Test)</span></p>
                <p class="text-secondary small">
                    Deutschsprachiger Kurztest: 7 Fragen, die mit Ja oder Nein beantwortet werden,
                    Summe 0&ndash;7. Deutlich schneller als der AUDIT und deshalb gut für das
                    Erstgespräch geeignet.
                </p>

                <hr>

                <p class="fw-medium mb-1">Woher kommen die Werte?</p>
                <p class="text-secondary small">
                    Beide Felder sind <strong>optional</strong>. Trage sie ein, wenn der Klient sie
                    aus einer Vorbehandlung, Suchtberatung oder Klinik mitbringt &ndash; oder wenn du
                    den Test selbst im Erstgespräch durchführst. Ist nichts erhoben, bleibt das Feld
                    leer; das ist kein Mangel.
                </p>

                <p class="fw-medium mb-1 mt-3">Wie sind sie einzuordnen?</p>
                <p class="text-secondary small mb-0">
                    Wie der ICD-Quick-Check sind beide <strong>Screening-Instrumente, keine Diagnostik</strong>.
                    Ein auffälliger Wert ist ein Anlass, die Suchtanamnese zu vertiefen &ndash; keine
                    Feststellung einer Abhängigkeit. Auch die obere Zone des AUDIT begründet nach dem
                    WHO-Manual die Abklärung, nicht den Befund.
                    Die klinische Diagnose obliegt dem Gutachter. Die Orientierungswerte stehen
                    direkt unter den Eingabefeldern.
                </p>

                <hr>
                <p class="text-secondary small mb-0">
                    <strong>Quellen.</strong> AUDIT: Babor, Higgins-Biddle, Saunders, Monteiro &ndash;
